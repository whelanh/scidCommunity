static thread_local int indentlevel;

void indent(){++indentlevel;};
void tab(){
  for(int i=0;i<indentlevel;++i) printf(" ");
}

void unindent(){
  indentlevel--;
  if(!indentlevel)indentlevel=0;
}
  

bool util::signedIntValue(const char* s, int* val){
  if (s==nullptr||s[0]==0) return false;
  bool negate=false;
  const char* next=s;
  if (next[0]=='-'){
    next++;
    negate=true;
  }
  if(!positiveIntValue(next,val))
    return false;
  if(negate){
    // Bound the magnitude before negating it: INT_MIN has no positive
    // counterpart, so anything above INT_MAX is refused instead of negated
    // (undefined behaviour) or wrapped. positiveIntValue() already enforces
    // that bound; the check is here so widening the number bound later cannot
    // silently reintroduce the overflow at this line.
    const int magnitude=*val;
    if(magnitude<0) return false;
    *val= -magnitude;
  }
  return true;
}
    
    
bool util::positiveIntValue(const char* s, int* val){
  if(!s||!*s)return false;
  int sum=0;
  while(char c=*s++){
    if (c>='0'&&c<='9'){
      const int digit=c-'0';
      // The query text is user input: :gamenumber 4294967297 wrapped to 1 and
      // quietly searched game 1. Refuse the range before it accumulates past
      // what an int can hold, so the query fails with a parse error instead of
      // matching something the user did not ask for.
      if(sum>(std::numeric_limits<int>::max()-digit)/10) return false;
      sum=sum*10+digit;
    }
    else return false;
  }
  *val=sum;
  return true;
}


string util::game_to_string(Game* game){
  // scidCommunity: scidvspc's CQL-specific WriteToPGN_CQL() is replaced by our
  // Game::WriteToPGN().
  std::pair<const char *, unsigned> pgn = game->WriteToPGN();
  uassert(pgn.first,"game_to_string internal");
  return {pgn.first, pgn.second};
}

void util::printgame(FILE* stream, Game* game){
  // scidCommunity: our TextBuffer has no DumpToFile(); see game_to_string().
  fputs(util::game_to_string(game).c_str(), stream);
}


void util::my_dump_board(boardT board){
  FILE* fp=stdout;
  printf("Side To move is: %c\n",board[COLOR_SQUARE]);
  for (int i=7; i>=0; i--) {
    fputs ("   ", fp);
    for (int j=0; j<8; j++) {
      const squareT s = static_cast<squareT>(i*8 + j);
      const char c=PIECE_CHAR[board[s]];
      if (c=='.'){
	if (i%2==j%2)
	  putc('+',fp);
	else
	  putc('-',fp);
      }
      else 
	putc (c, fp);
      putc (' ', fp);
    }
    putc ('\n', fp);
  }
}

int util::squareShiftDirection(int sq, directionT direction){
  uassert(sq>=0&&sq<64&&direction<=DOWN_RIGHT);
  const int s=CqlSquareMove(static_cast<squareT>(sq),direction);
  if (s>=64) return -1;
  return s;
}

bool util::directionCompatible(pieceT piece, directionT direction){
  const pieceT newp=piece_Type(piece);
  if (newp==ROOK||newp==QUEEN) return directionOrthogonal(direction);
  else if (newp==BISHOP||newp==QUEEN) return directionDiagonal(direction);
  else return false;
}
bool util::directionOrthogonal(directionT direction){
  return direction==UP||direction==DOWN||direction==LEFT||direction==RIGHT;
}

bool util::directionDiagonal(directionT direction){
  return direction==UP_LEFT||direction==DOWN_LEFT||direction==UP_RIGHT||direction==DOWN_RIGHT;
}

void util::printgame(Game* g){
  if(!g){printf("NULL GAME\n");}
  my_dump_board(g->GetCurrentPos()->GetBoard());
}
    
const char * util::string_append (const char* a, const char*b){
  uassert(a&&b,"string_append args");
  return util::copy((std::string(a)+b).c_str());
}

char * util::copy(const char * buffer){
  const std::size_t len=strlen(buffer);
  if (len>100000){
    fprintf(stderr,"Unfortunately, CQL cannot handle so many comments: game output of %zu bytes\n",len);
    fprintf(stderr,"Try modifying the .cql file to print fewer comments, for instance by using the 'silent' keyword.\n");
    fprintf(stderr,"Typically these comments are automatically generated by next or previous.\n");
    fprintf(stderr,"Try putting the keyword 'silent' in front of these keywords\n");
    fprintf(stderr,"or see the documentation for 'silent' for more options\n\n");
    fprintf(stderr,"Also consider the 'nestban' keyword if inside of a 'next' filter");
    fprintf(stderr,"Unable to handle so many comments, exiting\n");
    uassert(false);
  }
  char * nb=new char[len+1];
  std::memcpy(nb,buffer,len+1);
  return nb;
}
